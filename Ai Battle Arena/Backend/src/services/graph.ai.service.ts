import { StateSchema, MessagesValue, StateGraph, START, END, ReducedValue, type GraphNode } from "@langchain/langgraph";
import { HumanMessage } from "@langchain/core/messages";
import { z } from "zod"; // zod is a library for schema validation and type inference. It allows us to define the shape of our data and validate it at runtime. It also provides TypeScript types based on the schema we define.
import { mistralModel, cohereModel, geminiModel, groqModel } from "./model.service.js";
import { createAgent, providerStrategy, toolStrategy } from "langchain";

// if u are using any other model then gemini use toolStratergy
// START or END node shuru se hi hote hai langgraph mein inhe banana nhi padta

const state = new StateSchema({
    problem: z.string().default(""),
    solution_1: z.string().default(""),
    solution_2: z.string().default(""),
    judge: z.object({
        solution_1_score: z.number().min(0).max(10).default(0),
        solution_2_score: z.number().min(0).max(10).default(0),
        solution_1_reasoning: z.string().default(""),
        solution_2_reasoning: z.string().default(""),
    })
});

const solutionNode: GraphNode<typeof state> = async (state) => {
    const [groq_solution, cohere_solution] = await Promise.all([
        groqModel.invoke(state.problem),
        cohereModel.invoke(state.problem)
    ]);

    return {
        solution_1: groq_solution.text,
        solution_2: cohere_solution.text
    }
}

const judgeNode: GraphNode<typeof state> = async (state) => {
    const { problem, solution_1, solution_2 } = state;

    const judge = createAgent({
        model: geminiModel,
        responseFormat: providerStrategy(z.object({
            solution_1_score: z.number().min(0).max(10),
            solution_2_score: z.number().min(0).max(10),
            solution_1_reasoning: z.string(),
            solution_2_reasoning: z.string(),
        })),

        systemPrompt: `You are a judge tasked with evaluating two solutions generated by different AI models. Please provide a score out of 10 for each solution, along with your reasoning for the scores.`
    })

    const judgeResponse = await judge.invoke({
        messages: [
            new HumanMessage(`
                Problem: ${problem}
                Solution 1: ${solution_1}
                Solution 2: ${solution_2}
                please evaluate the solution and provide scores and reasoning.
                `)
        ]
    })

    console.log(judgeResponse);

    const {
        solution_1_score,
        solution_2_score,
        solution_1_reasoning,
        solution_2_reasoning,
    } = judgeResponse.structuredResponse

    return {
        judge: {
            solution_1_score,
            solution_2_score,
            solution_1_reasoning,
            solution_2_reasoning
        }
    }

}



const graph = new StateGraph(state)
                    .addNode("solution", solutionNode)
                    .addNode("judge_node", judgeNode)
                    .addEdge(START, "solution")
                    .addEdge("solution", "judge_node")
                    .addEdge("judge_node", END)
                    .compile()


export default async function(problem : string) {
    const result = await graph.invoke({
        problem: problem
    })

    return result
}

